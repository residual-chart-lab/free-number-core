"""Exact certificate for the transported-anchor transition groupoid at n=7.

For each reduced two-spectator support, enumerate every history obtained by

  1. deleting either spectator to reach the exact n=6 atlas,
  2. choosing any available direct seed chart,
  3. choosing a full-rank parent edge block, and
  4. carrying the deleted spectator when it is exterior to that edge.

For the five generic words this gives 17 histories but only 12 distinct
144-dimensional quotient coordinates.  The coordinates are generated by
three pair-local copies of the n=6 wall operator theta:

    A = (theta^{-1})_(H_R,V_a),
    B = (theta^{-1})_(H_R,V_b),
    S = -(theta)_(H_L,V_b).

The exceptional word 212 has three histories and two core coordinates.  Its
two full 148-dimensional coordinates are related by S direct-sum id_H: the
intrinsic kappa_212 residual is fixed and no residual-to-core shear occurs.

Every matching, completion, and transition is reconstructed independently
over F_1009 and F_1013.  Centered lifts agree and all defining identities are
then checked over the integers.  NumPy is used only for integer and
finite-field arithmetic; no floating-point computation occurs.
"""

